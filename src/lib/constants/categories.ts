/** Получение единой Lucide-иконки для любой категории маркетплейса */
export function getCategoryIcon(cat: string): LucideIcon {
  switch (cat.toLowerCase().trim()) {
    case "all":
    case "все товары":
    case "все":
      return LayoutGrid;
    case "одежда":
      return Shirt;
    case "обувь":
      return Footprints;
    case "сумки":
      return ShoppingBag;
    case "украшения":
      return Gem;
    case "косметика":
      return Sparkles;
    case "парфюмерия":
      return Droplets;
    case "еда":
    case "еда и напитки":
    case "стритфуд":
    case "фастфуд":
      return UtensilsCrossed;
    case "сладости и десерты":
    case "еда и десерты":
      return Cake;
    case "детские товары":
      return Baby;
    case "аксессуары":
      return Glasses;
    case "для дома":
    case "дом и декор":
      return Home;
    case "электроника":
      return Smartphone;
    case "спорт и отдых":
    case "спорт":
      return Dumbbell;
    case "автотовары":
      return Car;
    case "handmade":
    case "handmade и подарки":
      return Palette;
    case "разное":
      return Grid;
    default:
      return Tag;
  }
}

